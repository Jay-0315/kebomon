export type TranslationKey = keyof typeof dict.ko;

// vars가 있으면 "{{name}}" 형태의 자리표시자를 치환 — 확인창/메시지처럼 언어별로
// 어순이 달라지는(예: "{email}의 권한을 변경할까요?" vs "Change {email}'s role?") 문장에 사용.
export function translate(
  lang: Lang,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const raw = dict[lang]?.[key] ?? dict.ko[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{\{(\w+)\}\}/g, (_, name) => String(vars[name] ?? ""));
}
